"""Validate freestanding lasx_rt.elf and emit lasx_rt.bin + lasx_rt_meta.h."""

import struct
import sys

R_LARCH_NONE = 0
R_LARCH_RELATIVE = 3
SHT_SYMTAB = 2
SHT_DYNSYM = 11
SHT_RELA = 4
PT_LOAD = 1


def read_cstr(blob: bytes, off: int) -> str:
    end = blob.find(b"\x00", off)
    return blob[off:end].decode("utf-8", errors="replace")


def main() -> None:
    if len(sys.argv) != 4:
        print(f"Usage: {sys.argv[0]} <lasx_rt.elf> <lasx_rt.bin> <lasx_rt_meta.h>", file=sys.stderr)
        sys.exit(1)

    elf_path, out_bin_path, out_hdr_path = sys.argv[1], sys.argv[2], sys.argv[3]
    with open(elf_path, "rb") as f:
        elf = f.read()

    if elf[:4] != b"\x7fELF" or elf[4] != 2 or elf[5] != 1:
        raise RuntimeError("Expected 64-bit little-endian ELF")

    (
        _e_type,
        e_machine,
        _e_version,
        e_entry,
        e_phoff,
        e_shoff,
        _e_flags,
        _e_ehsize,
        e_phentsize,
        e_phnum,
        e_shentsize,
        e_shnum,
        _e_shstrndx,
    ) = struct.unpack_from("<HHIQQQIHHHHHH", elf, 16)

    if e_machine != 258:
        raise RuntimeError(f"Unexpected e_machine={e_machine}, expected EM_LOONGARCH (258)")
    if e_entry != 0:
        raise RuntimeError(f"lasx_rt_trap_entry must be at offset 0x0, got 0x{e_entry:x}")

    sections = []
    for i in range(e_shnum):
        off = e_shoff + i * e_shentsize
        sections.append(struct.unpack_from("<IIQQQQIIQQ", elf, off))

    syms = {}
    for sh in sections:
        sh_type = sh[1]
        sh_offset, sh_size, sh_link, _sh_info, _sh_align, sh_entsize = sh[4], sh[5], sh[6], sh[7], sh[8], sh[9]
        if sh_type in (SHT_SYMTAB, SHT_DYNSYM) and sh_entsize > 0:
            strtab_sh = sections[sh_link]
            strtab = elf[strtab_sh[4] : strtab_sh[4] + strtab_sh[5]]
            for pos in range(sh_offset, sh_offset + sh_size, sh_entsize):
                st_name, _st_info, _st_other, st_shndx, st_value, _st_size = struct.unpack_from(
                    "<IBBHQQ", elf, pos
                )
                name = read_cstr(strtab, st_name)
                if name:
                    syms[name] = (st_value, st_shndx)

    for req in ("__rt_image_start", "__data_start", "__file_end", "__rt_image_end", "lasx_rt_trap_entry"):
        if req not in syms:
            raise RuntimeError(f"Missing linker symbol {req}")

    data_start = syms["__data_start"][0]
    file_end = syms["__file_end"][0]
    image_end = syms["__rt_image_end"][0]

    if data_start % 0x4000 != 0 or image_end % 0x4000 != 0:
        raise RuntimeError(
            f"16KB alignment check failed: data_start=0x{data_start:x}, image_end=0x{image_end:x}"
        )

    rel_count = 0
    for sh in sections:
        sh_type, sh_flags = sh[1], sh[2]
        sh_offset, sh_size, sh_entsize = sh[4], sh[5], sh[9]
        if sh_type == SHT_RELA and (sh_flags & 0x2):
            for pos in range(sh_offset, sh_offset + sh_size, sh_entsize):
                r_offset, r_info, _r_addend = struct.unpack_from("<QQq", elf, pos)
                r_type = r_info & 0xFFFFFFFF
                r_sym = r_info >> 32
                if r_type == R_LARCH_NONE:
                    continue
                if r_type != R_LARCH_RELATIVE or r_sym != 0:
                    raise RuntimeError(
                        f"Unsupported dynamic relocation at 0x{r_offset:x}: type={r_type}, sym={r_sym}"
                    )
                if r_offset < data_start or r_offset + 8 > image_end:
                    raise RuntimeError(
                        f"Relocation target 0x{r_offset:x} outside writable RW segment [0x{data_start:x}, 0x{image_end:x})"
                    )
                rel_count += 1

    image = bytearray(file_end)
    for i in range(e_phnum):
        off = e_phoff + i * e_phentsize
        p_type, _p_flags, p_offset, p_vaddr, _p_paddr, p_filesz, _p_memsz, _p_align = struct.unpack_from(
            "<IIQQQQQQ", elf, off
        )
        if p_type != PT_LOAD or p_filesz == 0:
            continue
        end_va = min(p_vaddr + p_filesz, file_end)
        if end_va > p_vaddr:
            copy_len = end_va - p_vaddr
            image[p_vaddr : p_vaddr + copy_len] = elf[p_offset : p_offset + copy_len]

    with open(out_bin_path, "wb") as out_bin:
        out_bin.write(image)

    with open(out_hdr_path, "w", encoding="ascii") as out_hdr:
        out_hdr.write("/* Auto-generated by gen_rt_blob.py - DO NOT EDIT */\n")
        out_hdr.write("#ifndef LASX_RT_META_H\n")
        out_hdr.write("#define LASX_RT_META_H\n\n")
        out_hdr.write(f"#define LASX_RT_TEXT_SIZE  0x{data_start:x}UL\n")
        out_hdr.write(f"#define LASX_RT_FILE_SIZE  0x{file_end:x}UL\n")
        out_hdr.write(f"#define LASX_RT_TOTAL_SIZE 0x{image_end:x}UL\n\n")
        out_hdr.write("#endif /* LASX_RT_META_H */\n")

    print(
        f"[gen_rt_blob] OK: text=0x{data_start:x}, file=0x{file_end:x} ({file_end // 1024} KB), "
        f"total=0x{image_end:x}, R_LARCH_RELATIVE={rel_count}"
    )


if __name__ == "__main__":
    main()
